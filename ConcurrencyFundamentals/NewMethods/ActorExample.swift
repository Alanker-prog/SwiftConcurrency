import UIKit

actor Counter {
    
    private var value = 0
    
    func increment() {
        value += 1
    }
    
    func getValue() -> Int {
        value
    }
}

class ActorExample: UIViewController {
    
    override func viewDidLoad() {
        super.viewDidLoad()
        
        let counter = Counter()
        
        Task {
            await withTaskGroup(of: Void.self) { group in
                
                for _ in 0..<1000 {
                    group.addTask {
                        await counter.increment()
                    }
                }
            }
            
            let finalValue = await counter.getValue()
            print("Final value:", finalValue)
        }
    }
}

/*
