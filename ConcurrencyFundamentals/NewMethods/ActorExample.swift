    ◉ Actor — это ссылочный тип,
      который защищает своё состояние от Data Race.

    ◉ Только один поток может изменять
      состояние actor одновременно.

────────────────────────────────────────────

 🔥 В чём отличие от класса

    class:
        ◉ Не потокобезопасен
        ◉ Возможен Data Race

    actor:
        ◉ Изолирует состояние
        ◉ Гарантирует безопасный доступ

────────────────────────────────────────────

 🧠 Что происходит в примере

    ◉ 1000 задач параллельно вызывают increment()
    ◉ Но actor выполняет их последовательно
    ◉ Нет Data Race
    ◉ Результат всегда = 1000

────────────────────────────────────────────

 🔥 Почему нужен await

    ◉ Доступ к actor извне — асинхронный
    ◉ Swift гарантирует безопасную изоляцию
    ◉ Поэтому требуется await

────────────────────────────────────────────

 🛡 Чем actor заменяет старые инструменты

    Раньше:
        ◉ Serial Queue
        ◉ NSLock
        ◉ Semaphore
        ◉ Barrier

    Теперь:
        ◉ actor

────────────────────────────────────────────

 🟡 Пример из жизни

    Представь банковский счёт.

    Без actor:
        ◉ Несколько потоков могут менять баланс одновременно

    С actor:
        ◉ Только один доступ к балансу за раз

────────────────────────────────────────────

 ⚠️ Важно понимать

    ◉ Actor НЕ создаёт отдельный поток
    ◉ Он управляет доступом к состоянию
    ◉ Это изоляция, а не поток

────────────────────────────────────────────

 🧠 Главное, что нужно запомнить

    ◉ Actor решает проблему Data Race
    ◉ Гарантирует изоляцию состояния
    ◉ Требует await при обращении
    ◉ Это современный способ многопоточности
