import UIKit

class DeadlockExample: UIViewController {
    
    override func viewDidLoad() {
        super.viewDidLoad()
        
        print("Start")
        
        DispatchQueue.main.sync {
            print("This will never be printed")
        }
        
        print("End")
    }
}

/*
 🟢 Что такое Deadlock (Взаимная блокировка)

    ◉ Deadlock — это ситуация,
      когда два потока (или задачи)
      ждут друг друга бесконечно.

    ◉ В результате выполнение останавливается навсегда.

────────────────────────────────────────────

 🔥 Что происходит в примере

    viewDidLoad выполняется на Main Thread.

    Далее вызываем:

        DispatchQueue.main.sync { }

    ◉ sync означает — "подожди пока блок выполнится"
    ◉ Но main уже занят текущим кодом
    ◉ Он не может начать новый блок
    ◉ И одновременно ждёт его завершения

    → Взаимная блокировка
    → Приложение зависает

────────────────────────────────────────────

 🧠 Почему это происходит

    sync блокирует текущий поток.

    Если вызвать sync на той же очереди,
    на которой ты уже находишься —
    произойдёт Deadlock.

────────────────────────────────────────────

 ⚠️ Золотое правило

    НИКОГДА не вызывать sync
    на той же очереди,
    в которой ты уже находишься.

────────────────────────────────────────────

 🟡 Классическая схема Deadlock

        Queue A sync → Queue B
        Queue B sync → Queue A

    Оба ждут друг друга.
    Никто не продолжает выполнение.

────────────────────────────────────────────

 🟡 Пример из жизни

    Представь:

    ◉ Ты держишь ключ от комнаты
    ◉ И ждёшь, пока сам себе передашь этот ключ

    Это невозможно.
    Всё зависает.

────────────────────────────────────────────

 🛡 Как избежать Deadlock

    ◉ Использовать async вместо sync
    ◉ Не вызывать sync на текущей очереди
    ◉ Строить правильную архитектуру зависимостей

────────────────────────────────────────────

 🧠 Главное, что нужно запомнить

    ◉ Deadlock = взаимная блокировка
    ◉ sync блокирует текущий поток
    ◉ sync на той же очереди = гарантированный deadlock
    ◉ Очень часто спрашивают на собеседовании
 */
