import UIKit

class ThreadExample: UIViewController {
    
    override func viewDidLoad() {
        super.viewDidLoad()
        
        print("Main Thread:", Thread.isMainThread)
        print(Thread.current)
        
        DispatchQueue.global().async {
            print("Background Thread:", Thread.isMainThread)
            print(Thread.current)
        }
    }
}

/*
 🟢 Что такое Thread (Поток)

    ◉ Thread — это единица выполнения кода
    ◉ Процесс может содержать несколько потоков
    ◉ Каждый поток выполняет инструкции независимо

────────────────────────────────────────────

 🟢 Main Thread

    ◉ Главный поток приложения
    ◉ Отвечает за UI
    ◉ Обрабатывает события пользователя
    ◉ Любое обновление UI — только из main

    Thread.isMainThread → true

────────────────────────────────────────────

 🟢 Background Thread

    ◉ Фоновый поток
    ◉ Используется для тяжёлых задач:
        - загрузка данных
        - парсинг
        - вычисления
    ◉ Не должен блокировать UI

────────────────────────────────────────────

 🔥 Почему это важно

    Если тяжёлая операция выполняется на main:
        ◉ UI зависает
        ◉ Скролл тормозит
        ◉ Анимации лагают

    Поэтому:
        Тяжёлую работу → в background
        UI обновление → обратно в main

────────────────────────────────────────────

 🧠 Важно понимать

    ◉ Поток — это НЕ очередь
    ◉ DispatchQueue управляет потоками
    ◉ Система сама решает, какой поток использовать

────────────────────────────────────────────

 🟡 Пример из жизни

    Представь ресторан:

    ◉ Процесс = ресторан
    ◉ Потоки = официанты
    ◉ Main thread = главный официант (работа с клиентом)
    ◉ Background threads = кухня (готовка)

    Клиент (UI) не должен ждать, пока кухня готовит.

────────────────────────────────────────────

 ⚠️ Главное правило iOS

    UI обновляется ТОЛЬКО на main thread

    DispatchQueue.main.async {
        // обновление UI
    }

────────────────────────────────────────────

 🧠 Главное, что нужно запомнить

    ◉ Thread = единица выполнения
    ◉ Main thread отвечает за UI
    ◉ Фоновые потоки для тяжёлых задач
    ◉ Блокировка main = лаги интерфейса
 */
