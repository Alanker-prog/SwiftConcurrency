import UIKit

class DataRaceExample: UIViewController {
    
    var value = 0
    
    override func viewDidLoad() {
        super.viewDidLoad()
        
        DispatchQueue.global().async {
            self.value = 10
        }
        
        DispatchQueue.global().async {
            self.value = 20
        }
        
        DispatchQueue.main.asyncAfter(deadline: .now() + 1) {
            print("Final value:", self.value)
        }
    }
}

/*
 🟢 Что такое Data Race

    ◉ Data Race — это одновременный доступ к одной и той же
      области памяти из нескольких потоков,
      где хотя бы один доступ — запись,
      и отсутствует синхронизация.

────────────────────────────────────────────

 🔥 Что происходит в примере

    ◉ Два фоновых потока одновременно записывают value
    ◉ Нет контроля порядка
    ◉ Нет синхронизации
    ◉ Результат непредсказуем

────────────────────────────────────────────

 🧠 Формальное определение

    Data Race возникает, если:

    1️⃣ Два или более потоков
    2️⃣ Обращаются к одной переменной
    3️⃣ Хотя бы один из них записывает
    4️⃣ Нет синхронизации

────────────────────────────────────────────

 🔸 В чём отличие от Race Condition

    Race Condition:
        ◉ Более широкое понятие
        ◉ Ошибка логики порядка выполнения

    Data Race:
        ◉ Конкретно про одновременный доступ к памяти
        ◉ Низкоуровневая проблема

    Каждая Data Race — это Race Condition,
    но не каждая Race Condition — это Data Race.

────────────────────────────────────────────

 ⚠️ Почему это опасно

    ◉ Undefined behavior
    ◉ Повреждение памяти
    ◉ Краш приложения
    ◉ Непредсказуемые баги

────────────────────────────────────────────

 🛡 Как избежать Data Race

    ◉ Serial Queue
    ◉ Barrier
    ◉ NSLock
    ◉ Semaphore
    ◉ Actor (в Swift Concurrency)

────────────────────────────────────────────

 🟡 Пример из жизни

    Представь таблицу в Excel:

    ◉ Два человека редактируют одну ячейку одновременно
    ◉ Значение может "сломаться"

    Это Data Race.

────────────────────────────────────────────

 🧠 Главное, что нужно запомнить

    ◉ Data Race = одновременный доступ к памяти
    ◉ Хотя бы одна операция — запись
    ◉ Нет синхронизации
    ◉ Это уже технический уровень проблемы
 */
