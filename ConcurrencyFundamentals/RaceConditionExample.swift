import UIKit

class RaceConditionExample: UIViewController {
    
    var counter = 0
    
    override func viewDidLoad() {
        super.viewDidLoad()
        
        let queue = DispatchQueue.global()
        
        for _ in 0..<1000 {
            queue.async {
               // counter += 1
            }
        }
        
        DispatchQueue.main.asyncAfter(deadline: .now() + 1) {
            print("Final value:", self.counter)
        }
    }
}

/*
 🟢 Что такое Race Condition

    ◉ Race Condition — это ситуация,
      когда результат зависит от порядка выполнения потоков.

    ◉ Потоки "соревнуются" (race) за общий ресурс.

────────────────────────────────────────────

 🔥 Что происходит в примере

    ◉ 1000 фоновых задач увеличивают counter
    ◉ Ожидаем результат = 1000
    ◉ Но часто получаем меньше

    Почему?

────────────────────────────────────────────

 🧠 counter += 1 НЕ атомарная операция

    Это 3 шага:
        1. Прочитать значение
        2. Увеличить
        3. Записать обратно

    Если два потока выполняют это одновременно —
    данные перезаписываются.

────────────────────────────────────────────

 🟡 Что такое "общий ресурс"

    ◉ Любая переменная,
      к которой обращаются несколько потоков.

    В примере:
        counter — общий ресурс

────────────────────────────────────────────

 ⚠️ Почему это опасно

    ◉ Непредсказуемое поведение
    ◉ Случайные баги
    ◉ Сложно воспроизводится
    ◉ Может ломать бизнес-логику

────────────────────────────────────────────

 🛡 Как избежать Race Condition

    ◉ Serial Queue
    ◉ Barrier
    ◉ Lock / NSLock
    ◉ Semaphore (не решает все проблем)
    ◉ Actor (современный способ)

────────────────────────────────────────────

 🟡 Пример из жизни

    Представь банковский счёт:

    ◉ Два потока снимают деньги одновременно
    ◉ Баланс может стать неправильным

    Это race condition.

────────────────────────────────────────────

 🧠 Важно различать

    Race Condition — логическая проблема порядка выполнения.
    Data Race — одновременный доступ к памяти без синхронизации.

    (Data Race разберём отдельно.)

────────────────────────────────────────────

 🧠 Главное, что нужно запомнить

    ◉ Race Condition возникает при конкуренции потоков
    ◉ Общий ресурс = потенциальная проблема
    ◉ Операции чтения/записи не атомарны
    ◉ Требуется синхронизация
 */
