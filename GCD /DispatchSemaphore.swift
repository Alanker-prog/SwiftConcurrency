import UIKit

class SemaphoreExample: UIViewController {
    
    override func viewDidLoad() {
        super.viewDidLoad()
        
        let semaphore = DispatchSemaphore(value: 2)
        let queue = DispatchQueue.global(qos: .utility)
        
        for index in 1...5 {
            queue.async {
                
                semaphore.wait()
                
                print("Task \(index) started")
                sleep(2)
                print("Task \(index) finished")
                
                semaphore.signal()
            }
        }
    }
}

/*
 🟢 DispatchSemaphore(value: 2)

    ◉ Создаём семафор с начальным значением 2
    ◉ Одновременно могут выполняться только 2 задачи
    ◉ Остальные будут ждать освобождения

────────────────────────────────────────────

 🟢 semaphore.wait()

    ◉ Уменьшает счётчик на 1
    ◉ Если значение > 0 → поток продолжает работу
    ◉ Если значение = 0 → поток блокируется

────────────────────────────────────────────

 🟢 semaphore.signal()

    ◉ Увеличивает счётчик на 1
    ◉ Разблокирует один ожидающий поток

────────────────────────────────────────────

 🔸 Что происходит в примере

    ◉ Мы запускаем 5 задач
    ◉ Но одновременно выполняются только 2
    ◉ Остальные ждут, пока освободится "слот"

────────────────────────────────────────────

 🔸 Для чего используется DispatchSemaphore

    ◉ Ограничение количества одновременно выполняемых задач
    ◉ Контроль доступа к ресурсу
    ◉ Реализация пулов (например, максимум 3 сетевых запроса)

────────────────────────────────────────────

 ❗ Важно

    ◉ wait() блокирует поток
    ◉ Никогда не использовать на main thread
    ◉ Каждому wait() должен соответствовать signal()
    ◉ Иначе будет deadlock

────────────────────────────────────────────

 🟡 Пример из жизни

    Представь:
    ◉ Нужно загрузить 20 изображений
    ◉ Но сервер разрешает только 4 одновременных запроса

    Решение:
    ◉ Semaphore(value: 4)
    ◉ Одновременно выполняются только 4 загрузки
    ◉ Остальные ждут своей очереди

────────────────────────────────────────────

 🧠 Главное, что нужно запомнить

    ◉ Semaphore = счётчик доступа к ресурсу
    ◉ wait() блокирует поток
    ◉ signal() освобождает слот
    ◉ Неправильное использование → deadlock
 
 🔥 Маленькое понимание глубже
    ◉ Semaphore — это низкоуровневый механизм блокировки.
 В GCD его часто используют для:
    ◉ ограничения конкурентности  превращения async-кода в sync (что считается плохой практикой)‼️
 */
