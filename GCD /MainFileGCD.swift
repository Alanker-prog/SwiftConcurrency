import Foundation

/*
 ╔══════════════════════════════════════════════╗
 ║                GCD OVERVIEW                  ║
 ╚══════════════════════════════════════════════╝

 ──────────────────────────────────────────────
 🟢 1. DispatchQueue
 ──────────────────────────────────────────────

 ◉ Основной инструмент GCD
 ◉ Управляет выполнением задач

 Типы:
    ▸ serial      — одна задача за раз
    ▸ concurrent  — несколько задач параллельно
    ▸ main        — главный поток (UI)

 Методы:
    ▸ async       — не блокирует поток
    ▸ sync        — блокирует текущий поток


 ──────────────────────────────────────────────
 🟢 2. DispatchWorkItem
 ──────────────────────────────────────────────

 ◉ Управляемая задача
 ◉ Можно отменить (cancel)
 ◉ Можно добавить notify
 ◉ Даёт больше контроля, чем обычный async


 ──────────────────────────────────────────────
 🟢 3. DispatchGroup
 ──────────────────────────────────────────────

 ◉ Ожидание нескольких async задач
 ◉ notify вызывается, когда все задачи завершены
 ◉ Используется для координации


 ──────────────────────────────────────────────
 🟢 4. concurrentPerform
 ──────────────────────────────────────────────

 ◉ Параллельный цикл
 ◉ Синхронный метод
 ◉ Блокирует текущий поток
 ◉ Используется для CPU-heavy задач


 ──────────────────────────────────────────────
 🟢 5. .barrier
 ──────────────────────────────────────────────

 ◉ Работает только на concurrent очереди
 ◉ Даёт эксклюзивный доступ
 ◉ Паттерн: multiple readers / single writer
 ◉ Используется для thread-safe записи


 ──────────────────────────────────────────────
 🟢 6. DispatchSemaphore
 ──────────────────────────────────────────────

 ◉ Счётчик доступа к ресурсу
 ◉ wait() блокирует поток
 ◉ signal() освобождает слот
 ◉ Используется для ограничения количества задач


 ──────────────────────────────────────────────
 🟢 7. DispatchSource
 ──────────────────────────────────────────────

 ◉ Механизм обработки системных событий
 ◉ Работает через GCD

 Популярные типы:
    ▸ DispatchSourceTimer
    ▸ DispatchSourceRead (сокеты)
    ▸ DispatchSourceFileSystemObject
    ▸ DispatchSourceSignal


 ──────────────────────────────────────────────
 🟡 Как всё это связано
 ──────────────────────────────────────────────

 DispatchQueue
      ↓
 выполняет задачи

 DispatchWorkItem
      ↓
 управляемая задача

 DispatchGroup
      ↓
 координация задач

 concurrentPerform
      ↓
 параллельные вычисления

 barrier
      ↓
 безопасная запись

 semaphore
      ↓
 ограничение конкурентности

 DispatchSource
      ↓
 реакция на события системы


 ──────────────────────────────────────────────
 🧠 Когда что использовать
 ──────────────────────────────────────────────

 ◉ Просто выполнить код в фоне → async
 ◉ Нужен контроль задачи → DispatchWorkItem
 ◉ Нужно дождаться нескольких задач → DispatchGroup
 ◉ Нужен параллельный цикл → concurrentPerform
 ◉ Нужна безопасная запись → barrier
 ◉ Нужно ограничить количество задач → semaphore
 ◉ Нужен GCD-таймер или сокеты → DispatchSource


 ──────────────────────────────────────────────
 🚀 Современная альтернатива
 ──────────────────────────────────────────────

 Swift Concurrency:
    ▸ Task
    ▸ TaskGroup
    ▸ Actor

 Это более высокий уровень над GCD.
 GCD — фундамент.
 */
